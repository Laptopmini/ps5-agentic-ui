#!/usr/bin/env bash
# Cross-build ggml (Vulkan backend) + whisper.cpp as PS5 static libraries, for on-console
# speech-to-text (finding 25, Track B). The libs link into payload/console and drive the
# RADV GPU through the stock SDK libvulkan.so.1 — no Mihawk ps5-mesa fork, no native title.
#
#   scripts/ps5-ggml.sh            build (if the libs are missing) and install into payload/console/ggml
#   scripts/ps5-ggml.sh --rebuild  force a clean reconfigure + rebuild
#
# whisper.cpp is pinned below. Its source is cloned on the host (needs network) into
# payload/.ggml-src/ and built inside the payload-dev container; the products — five .a archives
# and the public headers — land in payload/console/ggml/ (git-ignored; regenerated by this script).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IMAGE=ps5-agentic-ui/payload-dev:0.41.1
PIN=v1.9.5                                   # whisper.cpp release (bundles ggml)
SRC="$ROOT/payload/.ggml-src"                # host clone (git-ignored)
OUT="$ROOT/payload/console/ggml"             # installed libs + headers (git-ignored)

[[ "${1:-}" == "--rebuild" ]] && rm -rf "$SRC/build-ps5" "$OUT"

# The libs are the slow part; skip if already installed and not forced.
if [[ -f "$OUT/lib/libggml-vulkan.a" && -f "$OUT/lib/libwhisper.a" && "${1:-}" != "--rebuild" ]]; then
  echo "ggml libs already present in $OUT (use --rebuild to force)" >&2
  exit 0
fi

if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
  echo "Building $IMAGE first…" >&2
  docker build -t "$IMAGE" "$ROOT/payload"
fi

# 1. Fetch the pinned whisper.cpp on the host (git in the container can't reach the network here).
if [[ ! -d "$SRC/whisper.cpp/.git" ]]; then
  echo "Cloning whisper.cpp $PIN …" >&2
  mkdir -p "$SRC"
  git clone --depth 1 --branch "$PIN" https://github.com/ggml-org/whisper.cpp "$SRC/whisper.cpp"
else
  (cd "$SRC/whisper.cpp" && [[ "$(git describe --tags 2>/dev/null)" == "$PIN" ]] || {
    echo "Checking out $PIN …" >&2; git fetch --depth 1 origin tag "$PIN"; git checkout -q "$PIN"; })
fi

# 2. Cross-configure + build inside the container.
#    - prospero.cmake: the SDK's cross toolchain (FreeBSD/x86_64, PIE, static libs).
#    - ggml-vulkan auto-builds its host-side vulkan-shaders-gen (CMAKE_CROSSCOMPILING) and
#      compiles the GLSL compute shaders with the image's glslc.
#    - SPIRV-Headers_DIR points at the apt package's cmake config (the cross find-root skips it);
#      /opt/sroot exposes ONLY spirv/ to the cross compile so host /usr/include can't leak in.
docker run --rm -v "$SRC:/work" "$IMAGE" bash -euc '
  mkdir -p /opt/sroot && ln -sfn /usr/include/spirv /opt/sroot/spirv
  cmake -S /work/whisper.cpp -B /work/build-ps5 \
    -DCMAKE_TOOLCHAIN_FILE=/opt/ps5-payload-sdk/toolchain/prospero.cmake \
    -DCMAKE_BUILD_TYPE=Release \
    -DGGML_VULKAN=ON -DGGML_NATIVE=OFF -DGGML_OPENMP=OFF \
    -DBUILD_SHARED_LIBS=OFF -DGGML_BACKEND_DL=OFF \
    -DWHISPER_BUILD_TESTS=OFF -DWHISPER_BUILD_EXAMPLES=OFF -DWHISPER_SDL2=OFF \
    -DSPIRV-Headers_DIR=/usr/share/cmake/SPIRV-Headers \
    -DCMAKE_CXX_FLAGS="-isystem /opt/sroot"
  cmake --build /work/build-ps5 -j"$(nproc)" --target whisper
'

# 3. Install the archives and public headers into the repo for the console link.
mkdir -p "$OUT/lib" "$OUT/include"
find "$SRC/build-ps5" -name 'libggml*.a' -o -name 'libwhisper.a' | while read -r a; do cp -f "$a" "$OUT/lib/"; done
cp -f "$SRC/whisper.cpp/ggml/include/"*.h "$OUT/include/"
cp -f "$SRC/whisper.cpp/include/whisper.h" "$OUT/include/"
echo "Installed ggml/whisper PS5 libs → $OUT/lib, headers → $OUT/include" >&2
ls -la "$OUT/lib"
